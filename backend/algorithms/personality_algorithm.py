def calculate_personality(answers: list[int]) -> dict:
    """
    根据20道题的答案计算旅行人格

    参数:
        answers: 20个整数，每个在1-5之间（1=非常不同意，5=非常同意）

    返回:
        包含人格类型、维度得分、详细解读的字典
    """
    if len(answers) != 20:
        raise ValueError("必须提供20个答案")

    # 初始化维度得分
    dimension_scores = {'P': 0, 'E': 0, 'S': 0, 'C': 0}
    dimension_counts = {'P': 0, 'E': 0, 'S': 0, 'C': 0}

    # 计算各维度原始得分
    for i, (dim, reverse) in enumerate(QUESTION_MAP):
        score = answers[i]
        if reverse:
            score = 6 - score  # 反向计分：1↔5, 2↔4, 3→3

        dimension_scores[dim] += score
        dimension_counts[dim] += 1

    # 计算各维度平均分（1-5分）
    dimension_avg = {}
    for dim in ['P', 'E', 'S', 'C']:
        dimension_avg[dim] = dimension_scores[dim] / dimension_counts[dim]

    # 判定每个维度的倾向
    # 平均分 >= 3 偏向A端（大写），< 3 偏向B端（小写）
    type_code = ''
    type_code += 'P' if dimension_avg['P'] >= 3 else 'W'
    type_code += 'E' if dimension_avg['E'] >= 3 else 'R'
    type_code += 'S' if dimension_avg['S'] >= 3 else 's'
    type_code += 'C' if dimension_avg['C'] >= 3 else 'c'

    # 获取人格类型信息
    personality = PERSONALITY_TYPES.get(type_code, PERSONALITY_TYPES['WRsc'])

    # 计算各维度倾向强度（0-100%）
    dimension_strength = {}
    for dim in ['P', 'E', 'S', 'C']:
        avg = dimension_avg[dim]
        strength = (avg - 1) / 4 * 100
        dimension_strength[dim] = round(strength, 1)

    return {
        'type_code': type_code,
        'personality': personality,
        'dimension_scores': dimension_avg,
        'dimension_strength': dimension_strength,
        'dimension_details': {
            'P': {
                'name': '规划性',
                'score': round(dimension_avg['P'], 2),
                'strength': dimension_strength['P'],
                'tendency': 'J人（计划控）' if dimension_avg['P'] >= 3 else 'P人（随性派）',
                'description': '你倾向于' + ('提前规划好一切，享受掌控感' if dimension_avg['P'] >= 3 else '随遇而安，享受不确定性带来的惊喜')
            },
            'E': {
                'name': '体验重心',
                'score': round(dimension_avg['E'], 2),
                'strength': dimension_strength['E'],
                'tendency': '肝帝（探索型）' if dimension_avg['E'] >= 3 else '咸鱼（享受型）',
                'description': '你更倾向于' + ('不断探索新地方、新事物' if dimension_avg['E'] >= 3 else '放慢脚步，享受当下的舒适')
            },
            'S': {
                'name': '社交模式',
                'score': round(dimension_avg['S'], 2),
                'strength': dimension_strength['S'],
                'tendency': 'e人（社交狂）' if dimension_avg['S'] >= 3 else 'i人（独行者）',
                'description': '你在旅行中更喜欢' + ('结识新朋友，分享快乐' if dimension_avg['S'] >= 3 else '独自探索，享受独处时光')
            },
            'C': {
                'name': '消费态度',
                'score': round(dimension_avg['C'], 2),
                'strength': dimension_strength['C'],
                'tendency': '蝗虫（集邮党）' if dimension_avg['C'] >= 3 else '貔貅（品质控）',
                'description': '你更倾向于' + ('多走多看，收集各种体验' if dimension_avg['C'] >= 3 else '少而精，追求品质而非数量')
            }
        }
    }


