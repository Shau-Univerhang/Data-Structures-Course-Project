/**
 * 获取指定城市的菜系标签列表
 * @param {string} cityName - 城市名称
 * @returns {string[]} 标签数组（包含「全部」）
 */
export function getCityCuisineTags(cityName) {
  if (!cityName) return CITY_CUISINE_CONFIG['西安']

  // 精确匹配
  if (CITY_CUISINE_CONFIG[cityName]) {
    return CITY_CUISINE_CONFIG[cityName]
  }

  // 模糊匹配
  for (const [key, tags] of Object.entries(CITY_CUISINE_CONFIG)) {
    if (cityName.includes(key) || key.includes(cityName)) {
      return tags
    }
  }

  // 兜底：通用标签
  return [
    '全部',
    '中餐正餐',
    '小吃快餐',
    '地方特色',
    '火锅',
    '烧烤',
    '甜品茶饮',
    '私房菜',
  ]
}

