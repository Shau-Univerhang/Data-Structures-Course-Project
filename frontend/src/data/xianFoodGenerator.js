/**
 * 按景点名 + 菜系类型 做维度统计
 * 用于验证每个景点每个菜系 ≥ 10 条
 */
export function getCategoryStats() {
  const data = generateRealFoodData()
  const stats = {}
  for (const [spotName, foods] of Object.entries(data.bySpot)) {
    const catCount = {}
    for (const f of foods) {
      catCount[f.type] = (catCount[f.type] || 0) + 1
    }
    stats[spotName] = {
      total: foods.length,
      categories: catCount,
    }
  }
  return stats
}

