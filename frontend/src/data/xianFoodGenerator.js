let _cachedData = null

/**
 * 生成全量真实美食数据
 * ————————————————————————————————————————
 * 对每个景点，从其所属美食圈取全部模板，逐条计算：
 *   - 经纬度（景点中心 + 确定性随机偏移）
 *   - 距离（Haversine 公式精确计算）
 *   - 评分/热度（基准值 ± 随机抖动）
 *   - 地址（景点区域后缀 + 模板地址核心）
 *
 * 返回值结构：
 *   {
 *     bySpot: { '华清宫': [...], '兵马俑': [...], ... },  // 12 个景点各自的美食列表
 *     byZone: { lintong: [...], city_center: [...], dayanta: [...] },  // 按美食圈（去重）
 *     all: [...],          // 全局去重列表（约 300 条）
 *     allViews: [...],     // 全量景点级视图（约 1000+ 条）
 *     cuisineTypes: [...], // 所有菜系类型
 *     spotNames: [...],    // 所有景点名
 *   }
 */
export function generateRealFoodData() {
  if (_cachedData) return _cachedData

  const bySpot = {}
  const byZone = { lintong: [], city_center: [], dayanta: [] }
  const allViews = []
  const seenTemplates = new Set() // 用于 byZone 去重

  // 全局唯一 ID 计数器
  let globalId = 0

  // 遍历每个景点
  for (const spot of SPOTS) {
    const zone = spot.zone
    const templates = ZONE_TEMPLATES[zone] || []
    const spotFoods = []

    for (let ti = 0; ti < templates.length; ti++) {
      const [name, type, baseRating, basePopularity, priceRange, tags, addressCore] = templates[ti]

      // 确定性种子：spot.id + template.index + spot.lng → 保证每次生成一致
      const seed = hashStr(spot.id + '_' + ti + '_' + spot.lng.toFixed(4))

      // 随机选择该景点的一个地址后缀
      const suffixIdx = Math.floor(mulberry32(seed + 1000)() * spot.suffixes.length)
      const suffix = spot.suffixes[suffixIdx]

      // 坐标偏移
      const [lng, lat] = offsetCoord(spot.lng, spot.lat, seed + 2000)

      // 精确距离
      const distance = Math.round(haversineM(spot.lng, spot.lat, lng, lat))

      // 评分/热度抖动
      const rating = Math.round(jitterRating(baseRating, seed + 3000) * 10) / 10
      const popularity = jitterPopularity(basePopularity, seed + 4000)

      // 全局唯一 ID
      globalId++
      const id = `xf_${String(globalId).padStart(4, '0')}`

      // 拼接完整地址：主干路名 + 细分位置
      const address = `西安市${addressCore}（${suffix}）`

      const foodEntry = {
        id,
        name,
        type,
        rating,
        popularity,
        distance,
        lnglat: [Math.round(lng * 1000000) / 1000000, Math.round(lat * 1000000) / 1000000],
        tags: [...tags],
        price_range: priceRange,
        address,
        // 元数据
        _spotId: spot.id,
        _spotName: spot.name,
        _zone: zone,
        _templateIdx: ti,
      }

      spotFoods.push(foodEntry)
      allViews.push(foodEntry)

      // 按美食圈去重（同一模板在不同景点下只保留一份）
      const templateKey = `${zone}_${ti}`
      if (!seenTemplates.has(templateKey)) {
        seenTemplates.add(templateKey)
        // 使用该景点下的第一条作为代表
        byZone[zone].push({ ...foodEntry })
      }
    }

    bySpot[spot.name] = spotFoods
  }

  // 全量去重列表
  const all = Object.values(byZone).flat()

  // 提取所有菜系类型
  const cuisineTypes = [...new Set(all.map((f) => f.type))].sort()

  // 所有景点名
  const spotNames = SPOTS.map((s) => s.name)

  _cachedData = {
    bySpot,
    byZone,
    all,
    allViews,
    cuisineTypes,
    spotNames,
    _spots: SPOTS,
    _zoneTemplates: ZONE_TEMPLATES,
  }

  return _cachedData
}

/**
 * 简单字符串哈希
 */
function hashStr(str) {
  let hash = 0
  for (let i = 0; i < str.length; i++) {
    const c = str.charCodeAt(i)
    hash = (hash << 5) - hash + c
    hash |= 0
  }
  return Math.abs(hash)
}

