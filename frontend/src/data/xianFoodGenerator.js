/**
 * 确定性伪随机数生成器 (Mulberry32)
 * 保证相同 seed 总是产出相同序列
 */
function mulberry32(a) {
  return function () {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/**
 * Haversine 距离计算（米）
 */
function haversineM(lng1, lat1, lng2, lat2) {
  const R = 6371000
  const toRad = (d) => (d * Math.PI) / 180
  const dLat = toRad(lat2 - lat1)
  const dLng = toRad(lng2 - lng1)
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLng / 2) ** 2
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
}

/**
 * 在景点中心点基础上做随机偏移（50m - 1500m）
 * @param {number} cLng 景点中心经度
 * @param {number} cLat 景点中心纬度
 * @param {number} seed 确定性种子
 * @returns {[number, number]} [lng, lat]
 */
function offsetCoord(cLng, cLat, seed) {
  const rng = mulberry32(seed)
  const angle = rng() * 2 * Math.PI
  // 偏重较近距离（平方根分布），但保证最小50m
  const radius = 50 + rng() * 1450
  const dx = radius * Math.cos(angle)
  const dy = radius * Math.sin(angle)
  const latPerM = 1 / 111320
  const lngPerM = 1 / (111320 * Math.cos((cLat * Math.PI) / 180))
  return [cLng + dx * lngPerM, cLat + dy * latPerM]
}

/**
 * 在范围内随机抖动评分
 */
function jitterRating(base, seed) {
  const rng = mulberry32(seed)
  const jitter = (rng() - 0.5) * 0.6
  return Math.max(3.5, Math.min(5.0, base + jitter))
}

/**
 * 在范围内随机抖动热度
 */
function jitterPopularity(base, seed) {
  const rng = mulberry32(seed)
  const jitter = (rng() - 0.5) * base * 0.6
  return Math.max(500, Math.round(base + jitter))
}

